/**
 * Builds src/styles/meeting.css from the meeting-software design stylesheet in the `non/` repo
 * (non/mytheus-web/app/mytheus.css), scoped so it can only ever style the Meeting tab.
 *
 *   node scripts/scope-meeting-css.mjs [path/to/mytheus.css]
 *
 * Every selector is prefixed with `.mx-meet`; the design's global element rules (`*`, `body`,
 * `button`, `a`, ...) become rules on the scope and its descendants; `:root` tokens move onto the
 * scope; keyframes are renamed `nm-*` so they cannot collide with the app's own animations. The
 * output is generated: change the source design and re-run, do not hand-edit it.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import postcss from "postcss";

const SCOPE = ".mx-meet";
const src = resolve(process.argv[2] ?? "../non/mytheus-web/app/mytheus.css");
const out = resolve("src/styles/meeting.css");

const root = postcss.parse(readFileSync(src, "utf8"), { from: src });

// 1. Rename keyframes and every reference to them.
const names = new Set();
root.walkAtRules("keyframes", (at) => {
  names.add(at.params);
  at.params = `nm-${at.params}`;
});
const nameRe = new RegExp(`\\b(${[...names].join("|")})\\b`, "g");
root.walkDecls(/^animation(-name)?$/, (d) => {
  d.value = d.value.replace(nameRe, "nm-$1");
});

// 2. Scope every selector.
const scopeOne = (sel) => {
  const s = sel.trim();
  if (s === ":root" || s === "html" || s === "body") return SCOPE;
  if (s === "*") return `${SCOPE} *`;
  return `${SCOPE} ${s}`;
};
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && rule.parent.name === "keyframes") return;
  rule.selectors = rule.selectors.map(scopeOne);
});

// 3. The design's body rule assumed it owned the whole page. Inside the app shell the scope is a
//    region of <main>, so drop the page-level sizing and scrolling it set.
root.walkRules((rule) => {
  if (rule.selector !== SCOPE) return;
  rule.walkDecls(/^(min-height|height|overflow|overflow-x|overflow-y)$/, (d) => d.remove());
});

const header =
  "/* GENERATED by scripts/scope-meeting-css.mjs from non/mytheus-web/app/mytheus.css.\n" +
  "   Do not edit by hand: change the design source and re-run the script. */\n\n";
writeFileSync(out, header + root.toString().trim() + "\n");
console.log(`wrote ${out}: ${names.size} keyframes renamed`);
